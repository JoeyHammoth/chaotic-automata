// The HashLife page. The tree lives in the wasm module, in a worker; this file decides what window
// to ask for, draws the answer at the level of detail the zoom implies, and reports the tree's own
// numbers.
//
// Three things are deliberate. First, a node smaller than a pixel draws as its density, so zooming
// out shows structure instead of noise. Second, the sharing ratio and the memory gauge are the
// engine's counts, not estimates: a page that guessed them would be lying about the compression.
// Third, the module runs off the main thread — the metapixel array takes seconds to read, and a page
// frozen for that long reads as a broken page.

import { looksLikeMacrocell, parseMacrocell } from './lib/macrocell';
import {
  createRemoteHashLife,
  type LoadedRemote,
  type Readout,
  type RemoteHashLife,
} from './lib/remote';
import { PatternError, parseRle, population, spread, type Pattern } from './lib/rle';
import {
  cellsPerPixel,
  clampView,
  formatSharing,
  formatStep,
  levelForScale,
  memory,
  stepOptions,
  type View,
} from './lib/view';

const SIZE = 640;
const GUN = `x = 36, y = 9, rule = B3/S23\r\n24bo$22bobo$12b2o6b2o12b2o$11bo3bo4b2o12b2o$2o8bo5bo3b2o$2o8bo3bob2o4bobo$10bo5bo7bo$11bo3bo$12b2o!`;
const BLOCK = 'x = 2, y = 2\n2o$2o!';
const LIBRARY: Record<string, string> = { gun: GUN, block: BLOCK };

interface Fixture {
  file: string;
  label: string;
  /** Where the pattern came from, printed with the load, so a reader can check the source. */
  source: string;
  tiles?: number;
  /** Read through the engine's macrocell reader, so no grid is materialised. */
  macrocell?: boolean;
}

// The two patterns that make the zoom worth having. Both are the published files, not
// reconstructions; the array is the metapixel tiled, so the source pattern stays the one that was
// published.
const FIXTURES: Record<string, Fixture> = {
  breeder: {
    file: 'fixtures/rileysbreeder.rle',
    label: "Riley's breeder",
    source: "conwaylife.com/wiki/Riley's_breeder — 38 cells, 135x41, quadratic growth",
  },
  metapixel: {
    file: 'fixtures/otcametapixel.rle',
    label: 'OTCA metapixel',
    source: 'conwaylife.com/wiki/OTCA_metapixel — 2058x2058, 64,691 cells, Brice Due 2006',
  },
  metapixelArray: {
    file: 'fixtures/otcametapixel-array.mc',
    label: 'OTCA metapixel, 2x2 array',
    // One copy per 4096-square, so the four copies are the same subtree and the tree shares them.
    // Edge to edge they cannot share — 2058 is not a power of two — and cost 2.3M nodes and 274 MB.
    // The file is generated by `npm run build:fixtures` from the published RLE above, and read by
    // the engine rather than flattened: as a byte grid the array is 38 MB.
    source: 'four copies of the OTCA metapixel, one per 4096-square: 987,560 nodes',
    macrocell: true,
  },
};

// Fixture text already in hand, keyed by file. The macrocell array is 1.7 MB and the page can be
// asked for the same pattern twice, so the second load is a read rather than another download and
// another decode; the tree is still built again, because that is the engine's work, not the file's.
const fetched = new Map<string, string>();

let hash: RemoteHashLife | null = null;
let view: View = { x: 0, y: 0, scale: 2 };
let step = 1;
let patternName = 'gun';
/** The root's level, kept from the last readout: the zoom handlers clamp against it synchronously. */
let rootLevel = 0;

function element<T extends HTMLElement>(id: string): T {
  const found = document.getElementById(id);
  if (found === null) throw new Error(`the page is missing #${id}`);
  return found as T;
}

function fail(message: string): void {
  const banner = element('error');
  banner.textContent = message;
  banner.hidden = false;
}

function status(message: string): void {
  element('status').textContent = message;
}

/** Say so when the engine is on this thread: the load then blocks the page instead of a worker. */
function noteThread(offThread: boolean): void {
  if (!offThread) {
    element('status').textContent +=
      " This browser cannot start a worker, so the engine runs on the page's own thread.";
  }
}

async function paint(life: RemoteHashLife, shown: Readout): Promise<void> {
  const canvas = element<HTMLCanvasElement>('plane');
  const context = canvas.getContext('2d');
  if (context === null) {
    fail('this browser has no 2d canvas context, so the plane cannot be drawn');
    return;
  }
  const level = levelForScale(view.scale, shown.level);
  const pixels = await life.view(level, Math.round(view.x), Math.round(view.y), SIZE);
  const image = context.createImageData(SIZE, SIZE);
  const area = Math.pow(4, level);
  for (let index = 0; index < SIZE * SIZE; index++) {
    const value = pixels[index] ?? 0;
    const offset = index * 4;
    // A node draws as its density: at level 0 that is the cell itself, above it the fraction of
    // the square that is alive.
    const density = value === 0 ? 0 : Math.min(1, value / area);
    const alive = density > 0 ? 0.25 + 0.75 * density : 0;
    image.data[offset] = Math.round(8 + (123 - 8) * alive);
    image.data[offset + 1] = Math.round(11 + (209 - 11) * alive);
    image.data[offset + 2] = Math.round(15 + (192 - 15) * alive);
    image.data[offset + 3] = 255;
  }
  context.putImageData(image, 0, 0);

  element('plane-caption').textContent =
    level === 0
      ? `One pixel per cell, ${cellsPerPixel(view.scale)} cell(s) per pixel.`
      : `One pixel per level-${level} node: each is drawn as the population density of a ${Math.pow(2, level)}×${Math.pow(2, level)} square.`;
}

function renderReadout(shown: Readout): void {
  const bounds = shown.bounds;
  element('readout').textContent =
    `generation ${shown.generation.toLocaleString('en-US')} · ` +
    `population ${shown.population.toLocaleString('en-US')} · ` +
    `root level ${shown.level} · ` +
    `live box ${bounds.maxX - bounds.minX + 1}×${bounds.maxY - bounds.minY + 1}`;
  element('step-note').textContent =
    `Each advance asks for ${formatStep(step)}; the engine decomposes that into the largest ` +
    'compressed steps the tree can hold, and falls back to a one-generation sweep when it cannot.';
}

function renderTree(shown: Readout): void {
  const body = element<HTMLTableSectionElement>('tree-table');
  body.replaceChildren();
  const rows: Array<[string, string]> = [
    ['nodes', shown.nodes.toLocaleString('en-US')],
    ['nominal cells', Math.pow(4, shown.level).toLocaleString('en-US')],
    ['sharing', formatSharing(shown.nodes, shown.level)],
    ['node cap', shown.cap.toLocaleString('en-US')],
    ['cap hits', shown.capHits.toLocaleString('en-US')],
    ['generation', shown.generation.toLocaleString('en-US')],
  ];
  for (const [label, value] of rows) {
    const row = document.createElement('tr');
    const name = document.createElement('th');
    name.scope = 'row';
    name.textContent = label;
    const cell = document.createElement('td');
    cell.textContent = value;
    row.append(name, cell);
    body.append(row);
  }
  const gauge = memory(shown.nodes, shown.cap);
  element('memory-gauge').setAttribute('aria-valuenow', String(Math.round(gauge.fraction * 100)));
  element('gauge-fill').style.width = `${Math.round(gauge.fraction * 100)}%`;
  element('gauge-label').textContent = `Memory: ${gauge.text}`;
  element('cap-note').textContent =
    shown.capHits > 0
      ? 'The cap has been hit: the tree is refusing to grow rather than exceeding its budget.'
      : 'The cap has not been hit.';
}

function syncUrl(shown: Readout): void {
  const url = new URL(window.location.href);
  url.searchParams.set('pattern', patternName);
  url.searchParams.set('gen', String(shown.generation));
  url.searchParams.set('scale', String(Math.round(view.scale * 1000) / 1000));
  url.searchParams.set('x', String(Math.round(view.x)));
  url.searchParams.set('y', String(Math.round(view.y)));
  window.history.replaceState(null, '', url);
}

async function render(): Promise<void> {
  if (hash === null) return;
  const shown = await hash.readout();
  rootLevel = shown.level;
  await paint(hash, shown);
  renderReadout(shown);
  renderTree(shown);
  syncUrl(shown);
}

function fit(shown: Readout): void {
  const bounds = shown.bounds;
  const span = Math.max(bounds.maxX - bounds.minX + 1, bounds.maxY - bounds.minY + 1, 1);
  view = clampView(
    {
      scale: Math.max(0.01, SIZE / (span * 1.4)),
      x: Math.max(0, bounds.minX - span * 0.2),
      y: Math.max(0, bounds.minY - span * 0.2),
    },
    Math.pow(2, shown.level),
  );
}

/** Adopt a tree the worker built: the page only decides what window to ask for. */
async function adopt(
  life: RemoteHashLife,
  name: string,
  summary: string,
  shown: Readout,
): Promise<void> {
  // The worker has already replaced the old tree with this one, so the old handle points at nothing
  // and has nothing of its own to release; this is the page letting go of it, not a teardown.
  if (hash !== null && hash !== life) hash.close();
  hash = life;
  patternName = name;
  rootLevel = shown.level;
  fit(shown);
  element('error').hidden = true;
  await render();
  // The status names the pattern last, so it never announces a tree the table has not drawn yet.
  status(summary);
}

async function load(pattern: Pattern, name: string): Promise<void> {
  let loaded: LoadedRemote;
  try {
    loaded = await createRemoteHashLife({ pattern });
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error));
    status('nothing to draw: the engine refused the pattern');
    return;
  }
  await adopt(
    loaded.life,
    name,
    `Loaded ${pattern.width}×${pattern.height}, ${population(pattern).toLocaleString('en-US')} ` +
      `live cells, ${pattern.rule ?? 'the default rule'}.`,
    loaded.readout,
  );
  noteThread(loaded.offThread);
}

/**
 * Load a macrocell through the engine's own reader. Nothing is flattened to a grid on the way: the
 * array is 38 MB as a byte grid and the module never allocates it.
 */
async function loadMacrocell(text: string, name: string): Promise<void> {
  let loaded: LoadedRemote;
  try {
    loaded = await createRemoteHashLife({ text });
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error));
    status('nothing to draw: the engine refused the macrocell');
    return;
  }
  const bounds = loaded.readout.bounds;
  await adopt(
    loaded.life,
    name,
    `Loaded ${bounds.maxX - bounds.minX + 1}×${bounds.maxY - bounds.minY + 1}, ` +
      `${loaded.readout.population.toLocaleString('en-US')} live cells from a macrocell.`,
    loaded.readout,
  );
  noteThread(loaded.offThread);
}

async function choosePattern(name: string): Promise<void> {
  const inline = LIBRARY[name];
  if (inline !== undefined) {
    await load(parseRle(inline), name);
    return;
  }
  const fixture = FIXTURES[name];
  if (fixture === undefined) return;
  const cached = fetched.get(fixture.file);
  status(cached === undefined ? `Fetching ${fixture.label}…` : `Reloading ${fixture.label}…`);
  try {
    let text = cached;
    if (text === undefined) {
      const response = await fetch(`${import.meta.env.BASE_URL}${fixture.file}`);
      if (!response.ok) throw new PatternError(`the pattern file is missing (${response.status})`);
      text = await response.text();
      fetched.set(fixture.file, text);
    }
    if (fixture.macrocell === true) {
      await loadMacrocell(text, name);
    } else {
      let pattern = looksLikeMacrocell(text) ? parseMacrocell(text) : parseRle(text);
      if (fixture.tiles !== undefined) pattern = spread(pattern, fixture.tiles, fixture.tiles);
      await load(pattern, name);
    }
    element('status').textContent += ` Source: ${fixture.source}.`;
  } catch (error) {
    const message = error instanceof PatternError ? error.message : String(error);
    fail(`Could not load ${fixture.label}: ${message}`);
  }
}

function wire(): void {
  const stepSelect = element<HTMLSelectElement>('step-size');
  for (const option of stepOptions()) {
    const node = document.createElement('option');
    node.value = String(option);
    node.textContent = formatStep(option);
    stepSelect.append(node);
  }
  stepSelect.value = String(step);
  stepSelect.addEventListener('change', () => {
    step = Number(stepSelect.value);
    void (async () => {
      if (hash === null) return;
      renderReadout(await hash.readout());
    })();
  });

  element('advance').addEventListener('click', () => {
    void (async () => {
      if (hash === null) return;
      if (!(await hash.step(step))) {
        fail('the engine refused that step: the node cap or the level limit stopped it');
      }
      await render();
    })();
  });

  element('zoom-in').addEventListener('click', () => {
    view = { ...view, scale: view.scale * 2 };
    if (hash !== null) view = clampView(view, Math.pow(2, rootLevel));
    void render();
  });

  element('zoom-out').addEventListener('click', () => {
    view = { ...view, scale: view.scale / 2 };
    if (hash !== null) view = clampView(view, Math.pow(2, rootLevel));
    void render();
  });

  element('fit').addEventListener('click', () => {
    void (async () => {
      if (hash === null) return;
      fit(await hash.readout());
      await render();
    })();
  });

  element<HTMLSelectElement>('pattern').addEventListener('change', (event) => {
    const target = event.target as HTMLSelectElement;
    void choosePattern(target.value);
  });

  element('import').addEventListener('click', () => {
    const text = element<HTMLTextAreaElement>('paste').value;
    try {
      const pattern = looksLikeMacrocell(text) ? parseMacrocell(text) : parseRle(text);
      element('import-note').textContent =
        `Read ${pattern.width}×${pattern.height}, ${population(pattern).toLocaleString('en-US')} ` +
        `live cells, from ${pattern.format}.`;
      void load(pattern, 'pasted');
    } catch (error) {
      const message = error instanceof PatternError ? error.message : String(error);
      element('import-note').textContent = `Could not read that pattern: ${message}`;
    }
  });

  element<HTMLCanvasElement>('plane').addEventListener(
    'wheel',
    (event: WheelEvent) => {
      if (hash === null) return;
      event.preventDefault();
      const factor = event.deltaY < 0 ? 2 : 0.5;
      view = clampView({ ...view, scale: view.scale * factor }, Math.pow(2, rootLevel));
      void render();
    },
    { passive: false },
  );
}

function start(): void {
  wire();
  const params = new URLSearchParams(window.location.search);
  const requested = params.get('pattern') ?? 'gun';
  const text = LIBRARY[requested] ?? GUN;
  patternName = LIBRARY[requested] === undefined ? 'gun' : requested;
  const pattern = parseRle(text);
  void load(pattern, patternName).then(async () => {
    if (hash === null) return;
    // `Number(null)` is 0, which would look finite and clamp the view to the coarsest level, so a
    // missing parameter is checked for by name rather than by value.
    const scale = Number(params.get('scale'));
    const x = Number(params.get('x'));
    const y = Number(params.get('y'));
    const placed = params.has('scale') && params.has('x') && params.has('y');
    if (placed && Number.isFinite(scale) && scale > 0 && Number.isFinite(x) && Number.isFinite(y)) {
      view = clampView({ scale, x, y }, Math.pow(2, rootLevel));
    }
    const gen = Number(params.get('gen'));
    if (Number.isInteger(gen) && gen > 0) {
      await hash.step(gen);
    }
    await render();
  });
}

start();
